import json, os

class M:
    def __init__(s, w, h):
        s.w, s.h = w, h
        s.g = [['#'] * w for _ in range(h)]
    def room(s, x0, y0, x1, y1, ch='.'):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                s.g[y][x] = ch
        return s
    def wall(s, x0, y0, x1=None, y1=None):
        x1 = x0 if x1 is None else x1
        y1 = y0 if y1 is None else y1
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                s.g[y][x] = '#'
        return s
    def put(s, x, y, ch):
        if not (0 <= x < s.w and 0 <= y < s.h):
            raise SystemExit(f'out of bounds {x},{y} {ch}')
        if len(ch) != 1:
            raise SystemExit(f'bad char {ch}')
        if ch in '§,¤¥' and s.g[y][x] != '.':
            raise SystemExit(f'cell {x},{y} not free for {ch}: {s.g[y][x]!r}')
        s.g[y][x] = ch
        return s
    def void_outside(s):
        # الصخر الخارجي فقط (المتصل بحافة الخريطة ولا يجاور أرضية) يصبح فراغاً مظلماً
        def deep(x, y):
            if s.g[y][x] != '#':
                return False
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    X, Y = x + dx, y + dy
                    if 0 <= X < s.w and 0 <= Y < s.h and s.g[Y][X] not in '# ':
                        return False
            return True
        seen = set()
        stack = [(x, y) for x in range(s.w) for y in (0, s.h - 1)] + [(x, y) for y in range(s.h) for x in (0, s.w - 1)]
        while stack:
            x, y = stack.pop()
            if (x, y) in seen or not (0 <= x < s.w and 0 <= y < s.h) or not deep(x, y):
                continue
            seen.add((x, y))
            stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
        for (x, y) in seen:
            s.g[y][x] = ' '
        return s
    def rows(s):
        return [''.join(r) for r in s.g]

