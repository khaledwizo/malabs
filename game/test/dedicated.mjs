// اختبار تطبيق السيرفر المنفصل: صفحة السيرفر + لاعب يدخل برمز الغرفة من شاشة الأصدقاء
import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
import { spawn } from 'child_process';
import path from 'path';
const broker = spawn('node', ['test/broker.mjs', '8883', '20'], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 600));
const BR = '?broker=ws://localhost:8883/mqtt&nortc';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errs = [];
const S = await (await b.newContext()).newPage(); S.on('pageerror', e => errs.push('srv ' + e.message));
await S.goto('file://' + path.resolve('dist/server.html') + BR);
await S.waitForFunction(() => window.__srv && window.__srv() && window.__srv().link && window.__srv().link.mqs.length > 0, null, { timeout: 15000 });
const room = await S.evaluate(() => window.__srv().room); console.log('room', room);
const P = await (await b.newContext({ viewport: { width: 640, height: 360 } })).newPage(); P.on('pageerror', e => errs.push('cli ' + e.message));
await P.addInitScript(() => localStorage.setItem('rafidain.settings.v2', JSON.stringify({ quality: 'low', fps: 0, name: 'خالد' })));
await P.goto('file://' + path.resolve('dist/index.html') + BR); await P.waitForTimeout(2500);
await P.evaluate(r => { window.__R.UI.open('friends'); document.querySelector('.srvjoin').open = true; document.querySelector('#srvCode').value = r; document.querySelector('#srvGo').click(); }, room);
await P.waitForTimeout(8000);
console.log('client', JSON.stringify(await P.evaluate(() => { const s = window.__R.game.sim; return s ? { state: s.state, phase: s.phase, mode: s.mode, tdm: s.tdm, players: [...s.players.values()].map(p => p.name + (p.bot ? '*' : '')).join(' ') } : null; })));
console.log('server', JSON.stringify(await S.evaluate(() => { const I = window.__srv().info(); return { phase: I.phase, mode: I.mode, tick: I.tick, humans: I.players.filter(p => !p.bot).map(p => p.name) }; })));
console.log(errs.slice(0, 6).join('\n'));
await b.close(); broker.kill();
